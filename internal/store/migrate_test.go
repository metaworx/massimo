// migrations/store.sql is the store's schema as the migrations beside it
// leave an empty file (docs/store.md section 5, "Migrations"; AP Logging
// v1.1, Block 2): for reading, and for a review, where a migration's pull
// request shows its effect as a difference of the file. A store is made
// by the migrations, never from this file, and the binary does not
// embed it.

import (
	"context"
	"flag"
	"fmt"
	"io/fs"
	"os"
	"sort"
	"strings"
	"testing"
)

// updateStoreSQL makes TestStoreSQL write migrations/store.sql again:
// go test ./internal/store -run TestStoreSQL -update
var updateStoreSQL = flag.Bool("update", false, "TestStoreSQL writes migrations/store.sql again")

// storeSQL is the generated schema, among the migrations; storeSQLName
// is its name there.
const (
	storeSQL     = "migrations/" + storeSQLName
	storeSQLName = "store.sql"
)

// storeSQLHeader heads store.sql; %d are the schema version and its
// min_reader.
const storeSQLHeader = `-- SPDX-License-Identifier: AGPL-3.0-or-later
-- Copyright (C) 2026 The Massimo Authors
--
-- The store's schema at version %d (min_reader %d), as the migrations in
-- this directory leave an empty file: every table, each followed by its
-- indexes, by name. Generated by TestStoreSQL (../migrate_test.go), never
-- edited by hand: after a new migration, write it again with
--   go test ./internal/store -run TestStoreSQL -update
-- and commit it with the migration. It is no migration and the binary
-- does not embed it. The rows the migrations insert (the roles, the
-- capabilities, the node and tenant ids) are not in it, and a store is
-- made by the migrations, not from this file (docs/store.md,
-- "Migrations").
`

// schemaSQL is the schema of a store's file as store.sql holds it: the
// header, then every table's statement as SQLite keeps it, followed by
// those of its indexes, then any other object, each group by name.
func schemaSQL(ctx context.Context, s *Store) (string, error) {
	rows, err := s.db.QueryContext(ctx, `SELECT type, name, tbl_name, sql FROM sqlite_master
		WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'`)
	if err != nil {
		return "", err
	}
	defer rows.Close()
	type object struct{ typ, name, table, sql string }
	var tables, others []object
	indexes := map[string][]object{}
	for rows.Next() {
		var o object
		if err := rows.Scan(&o.typ, &o.name, &o.table, &o.sql); err != nil {
			return "", err
		}
		switch o.typ {
		case "table":
			tables = append(tables, o)
		case "index":
			indexes[o.table] = append(indexes[o.table], o)
		default:
			others = append(others, o)
		}
	}
	if err := rows.Err(); err != nil {
		return "", err
	}
	byName := func(l []object) {
		sort.Slice(l, func(i, j int) bool { return l[i].name < l[j].name })
	}
	byName(tables)
	byName(others)
	v, mr := s.SchemaVersion()
	var b strings.Builder
	fmt.Fprintf(&b, storeSQLHeader, v, mr)
	write := func(o object) { fmt.Fprintf(&b, "\n%s;\n", strings.TrimSpace(o.sql)) }
	for _, t := range tables {
		write(t)
		ix := indexes[t.name]
		byName(ix)
		for _, i := range ix {
			write(i)
		}
		delete(indexes, t.name)
	}
	if len(indexes) > 0 {
		return "", fmt.Errorf("indexes of no table: %v", indexes)
	}
	for _, o := range others {
		write(o)
	}
	return b.String(), nil
}

// migrations/store.sql says what the migrations make of an empty file;
// -update writes it again.
func TestStoreSQL(t *testing.T) {
	s := open(t, t.TempDir())
	got, err := schemaSQL(context.Background(), s)
	if err != nil {
		t.Fatal(err)
	}
	if *updateStoreSQL {
		if err := os.WriteFile(storeSQL, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	b, err := os.ReadFile(storeSQL)
	if err != nil {
		t.Fatalf("%v: write it with go test ./internal/store -run TestStoreSQL -update", err)
	}
	want := strings.ReplaceAll(string(b), "\r\n", "\n")
	if got == want {
		return
	}
	g, w := strings.Split(got, "\n"), strings.Split(want, "\n")
	for i := 0; i < len(g) || i < len(w); i++ {
		var gl, wl string
		if i < len(g) {
			gl = g[i]
		}
		if i < len(w) {
			wl = w[i]
		}
		if gl != wl {
			t.Fatalf("%s differs from the migrations at line %d:\n  file:       %q\n  migrations: %q\n"+
				"after a new migration, write it again with go test ./internal/store -run TestStoreSQL -update",
				storeSQL, i+1, wl, gl)
		}
	}
}

// Every file of migrations/ is a numbered migration, which loadMigrations
// would otherwise skip without a word, or store.sql; the binary embeds
// exactly the numbered ones.
func TestMigrationFilesNamed(t *testing.T) {
	entries, err := os.ReadDir("migrations")
	if err != nil {
		t.Fatal(err)
	}
	var numbered []string
	for _, e := range entries {
		switch {
		case e.Name() == storeSQLName:
		case migrationName.MatchString(e.Name()):
			numbered = append(numbered, e.Name())
		default:
			t.Errorf("migrations/%s: neither a migration NNNN_<name>.sql nor %s", e.Name(), storeSQLName)
		}
	}
	embeddedNames, err := fs.Glob(embeddedMigrations(), "*")
	if err != nil {
		t.Fatal(err)
	}
	if strings.Join(embeddedNames, " ") != strings.Join(numbered, " ") {
		t.Fatalf("embedded %v, the numbered migrations %v", embeddedNames, numbered)
	}
}
