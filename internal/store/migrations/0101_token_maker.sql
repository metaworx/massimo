-- A key names the key that made it (AP KeyLife v1.0, Block 2, D5-A;
-- docs/store.md section 6, "Keys made by keys"): tokens.made_by is the
-- row of the API key that was the bearer of the POST
-- /api/v1/users/{name}/tokens that made this key, NULL for every other
-- token: a key made by a session, by the command line, by the bootstrap
-- or at an integration's collection of its key, and a session. Revoking
-- a key revokes the keys it made, and theirs; a key's end takes none.
-- The second number of main's block, after 0100_token_revoke
-- (docs/store.md, "Two lines of releases"). Additive: a binary for 24 to
-- 100 reads the file and writes its tokens without the column, so a key
-- it makes has no maker, and its revoke of a key leaves the keys that
-- key made, which this binary's revoke of the key's own maker still
-- reaches, the makers followed through a revoked key. No foreign key, so
-- that the down part can drop the column.
ALTER TABLE tokens ADD COLUMN made_by INTEGER;
CREATE INDEX tokens_made_by ON tokens (made_by) WHERE made_by IS NOT NULL;
